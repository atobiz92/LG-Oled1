// Adds images to the existing wallpaper catalog instead of rebuilding it (prepare-wallpapers.mjs
// rewrites src/js/wallpapers.js from one folder and would drop everything else, including the
// hand-translated titles). Same output: 1920x1080 cover crop with the readability scrim baked in.
//
//   node scripts/add-wallpapers.mjs <folder> [file …]
//
// Titles come from the file name ("84-topografie-der-verbindung" → "Topografie der verbindung");
// German noun capitals are not guessed, so check the titles in src/js/wallpapers.js afterwards.
// An entry whose key already exists is replaced in place.
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync, mkdirSync, rmSync, statSync, readdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { basename, extname, join, resolve } from 'node:path';

const CHROME = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const root = resolve(import.meta.dirname, '..');
const outDir = join(root, 'src/img/wallpapers');
const thumbDir = join(outDir, 'thumbs');
const catalogFile = join(root, 'src/js/wallpapers.js');

// Kept identical to prepare-wallpapers.mjs so old and new wallpapers read the same.
const SCRIM = [
    'radial-gradient(1300px 700px at 0% 0%, rgba(0,0,0,0.55), rgba(0,0,0,0) 70%)',
    'linear-gradient(to bottom, rgba(0,0,0,0.25) 0%, rgba(0,0,0,0.30) 30%, rgba(0,0,0,0.62) 62%, rgba(0,0,0,0.82) 100%)'
].join(',');

const sourceDir = resolve(process.argv[2] || '');
if (!statSync(sourceDir, { throwIfNoEntry: false })?.isDirectory()) {
    console.error('Usage: node scripts/add-wallpapers.mjs <folder> [file …]');
    process.exit(1);
}
const files = process.argv.length > 3 ? process.argv.slice(3)
    : readdirSync(sourceDir).filter((f) => /\.(jpe?g|png|webp)$/i.test(f)).sort();

// "84-topografie-der-verbindung" → key "topografie-der-verbindung", title "Topografie der Verbindung".
// ae/oe/ue become umlauts except after q or a vowel (Quelle, Feuer stay as they are).
function naming(file) {
    const key = basename(file, extname(file)).toLowerCase().replace(/^\d+[-_ ]*/, '')
        .replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 40);
    const words = key.split('-').join(' ')
        .replace(/([^qaeiou])ae/g, '$1ä').replace(/([^qaeiou])oe/g, '$1ö').replace(/([^qaeiou])ue/g, '$1ü');
    return { key, title: words.charAt(0).toUpperCase() + words.slice(1) };
}

function readCatalog() {
    const text = readFileSync(catalogFile, 'utf8');
    return JSON.parse(text.slice(text.indexOf('['), text.lastIndexOf(']') + 1));
}

mkdirSync(thumbDir, { recursive: true });
const tmp = mkdtempSync(join(tmpdir(), 'wallpapers-'));
const catalog = readCatalog();

for (const file of files) {
    const { key, title } = naming(file);
    const html = join(tmp, key + '.html');
    const png = join(tmp, key + '.png');
    const src = 'file://' + join(sourceDir, file).split('/').map(encodeURIComponent).join('/');
    writeFileSync(html, `<!DOCTYPE html><body style="margin:0;width:1920px;height:1080px;background:${SCRIM},` +
        `url('${src}') center / cover no-repeat #000"></body>`);
    execFileSync(CHROME, ['--headless=new', '--disable-gpu', '--hide-scrollbars', '--window-size=1920,1080',
        '--allow-file-access-from-files', '--virtual-time-budget=5000', `--user-data-dir=${join(tmp, 'profile')}`,
        `--screenshot=${png}`, 'file://' + html], { stdio: 'ignore' });
    const out = join(outDir, key + '.jpg');
    execFileSync('sips', ['-s', 'format', 'jpeg', '-s', 'formatOptions', '82', png, '--out', out], { stdio: 'ignore' });
    execFileSync('sips', ['-Z', '320', '-s', 'formatOptions', '78', out, '--out', join(thumbDir, key + '.jpg')], { stdio: 'ignore' });
    const entry = { key, title, file: 'img/wallpapers/' + key + '.jpg', thumb: 'img/wallpapers/thumbs/' + key + '.jpg', credit: '' };
    const at = catalog.findIndex((w) => w.key === key);
    if (at >= 0) catalog[at] = entry; else catalog.push(entry);
    console.log(`${key}.jpg  ${(statSync(out).size / 1024).toFixed(0)} KB  „${title}“`);
}
rmSync(tmp, { recursive: true, force: true });

writeFileSync(catalogFile,
    '/* Generated by scripts/prepare-wallpapers.mjs, extended by scripts/add-wallpapers.mjs.\n' +
    '   Photos: Unsplash License; entries without credit are the owner\'s own images. */\n' +
    'window.WALLPAPERS = ' + JSON.stringify(catalog, null, 4) + ';\n');
console.log(`${catalog.length} entries in src/js/wallpapers.js`);
