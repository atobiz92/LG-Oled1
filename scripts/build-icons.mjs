// Lucide icons for Settings (and the Home glow's sibling UI), as inline SVG markup in src/js/icons.js.
//
//   node scripts/build-icons.mjs [--from <lucide-dir>]
//
// --from copies the icons listed below, unchanged, from a Lucide folder (the Ordiscale brand package:
// Ordiscale-Marke/build/paket/04-icons/lucide-komplett) into src/img/icons/, with LICENSE and VERSION.txt.
// Without it the copies already in src/img/icons/ are used. Then src/js/icons.js is written: the inner
// markup of every icon, so the app draws them inline with stroke="currentColor" (an <img> or an
// external <use> could not take the text colour, and external <use> is blocked on file:// pages).
import { readFileSync, writeFileSync, copyFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'src/img/icons');

// Every icon the app uses; add the name here, then run the script.
const NAMES = [
    'a-large-small', 'calendar', 'calendar-check', 'calendar-days', 'check', 'chevron-right', 'circle-user-round', 'circle-x', 'clock-3',
    'cloud-off', 'cloud-sun', 'eye', 'flag', 'flask-conical', 'gamepad-2', 'house', 'image', 'images',
    'key-round', 'languages', 'layout-grid', 'log-in', 'log-out', 'map-pin', 'monitor-play', 'moon', 'moon-star', 'music-2',
    'network', 'panels-top-left', 'play', 'plug-zap', 'plus', 'refresh-cw', 'rocket', 'rotate-ccw', 'router',
    'server', 'shapes', 'shield-check', 'signal', 'sliders-horizontal', 'smartphone', 'square-arrow-out-up-right', 'tag',
    'text-quote', 'timer', 'trash-2', 'triangle-alert', 'tv', 'type', 'upload', 'volume-2', 'wand-sparkles',
    'wifi',
    // Home Assistant "Sicherheit" (js/ha-view.js) and its settings
    'activity', 'app-window', 'bell-ring', 'cctv', 'door-closed', 'door-open', 'layers-2', 'lock', 'lock-open',
    'shield', 'shield-alert', 'video', 'warehouse'
];

const from = process.argv.indexOf('--from') >= 0 ? process.argv[process.argv.indexOf('--from') + 1] : null;
mkdirSync(out, { recursive: true });
if (from) {
    for (const f of ['LICENSE', 'VERSION.txt'].concat(NAMES.map((n) => n + '.svg'))) {
        copyFileSync(join(from, f), join(out, f));
    }
}

const icons = {};
for (const name of NAMES) {
    const file = join(out, name + '.svg');
    if (!existsSync(file)) throw new Error('Missing ' + file + ' (run with --from <lucide-dir>)');
    const svg = readFileSync(file, 'utf8');
    const inner = /<svg[^>]*>([\s\S]*)<\/svg>/.exec(svg);
    if (!inner) throw new Error('No <svg> in ' + file);
    icons[name] = inner[1].replace(/\s*\n\s*/g, '').replace(/\s*\/>/g, '/>').trim();
}

const version = readFileSync(join(out, 'VERSION.txt'), 'utf8').trim();
const body = Object.keys(icons).map((n) => '    ' + JSON.stringify(n) + ': ' + JSON.stringify(icons[n])).join(',\n');
writeFileSync(join(root, 'src/js/icons.js'), `/*
 * Generated by scripts/build-icons.mjs, do not edit. Lucide icons (${version}, ISC licence, src/img/icons/LICENSE),
 * copied unchanged from the Ordiscale brand package: 24 grid, stroke 2, round caps and joins.
 */
(function () {
    'use strict';

    var ICONS = {
${body}
    };

    // Inline SVG in the text colour (stroke="currentColor"); an unknown name draws nothing.
    function icon(name, className) {
        return '<svg' + (className ? ' class="' + className + '"' : '') + ' viewBox="0 0 24 24" fill="none" ' +
            'stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">' +
            (ICONS[name] || '') + '</svg>';
    }

    window.Icons = { svg: icon, has: function (name) { return !!ICONS[name]; } };
})();
`);
console.log('icons.js: ' + NAMES.length + ' icons');
